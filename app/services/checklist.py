def extra_items_for_transmission(transmission: str | None) -> list[ChecklistItem]:
    if not transmission:
        return []
    t = transmission.lower()
    if any(x in t for x in ("робот", "dsg", "amt")):
        return [
            ChecklistItem(
                zone="КПП",
                title="Роботизированная коробка",
                how_to_check=(
                    "На парковке несколько раз трогайтесь с места и в пробке — без рывков и запаха сцепления. "
                    "На скорости плавные переключения без «ударов»."
                ),
                tools=["OBD-II сканер"],
                red_flags=["рывки с места", "перегрев", "ошибки по муфте"],
            )
        ]
    if "вариатор" in t:
        return [
            ChecklistItem(
                zone="КПП",
                title="Вариатор CVT",
                how_to_check="Проверьте плавность разгона без пробуксовки и постороннего вой. История замены масла CVT.",
                tools=["OBD-II сканер"],
                red_flags=["пробуксовка", "вой при разгоне"],
            )
        ]
    return []


def build_checklist(transmission: str | None = None) -> list[ChecklistItem]:
    items = list(BASE_CHECKLIST)
    items.extend(extra_items_for_transmission(transmission))
    return items
